const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const listeners = {}, events = [], timers = [];
const document = {hidden: false, hasFocus: () => true, addEventListener: (n, f) => listeners[n] = f};
const window = {location: {origin: 'https://arxiv.gg'}, gtag: (...a) => events.push(a), setInterval: f => timers.push(f)};
const context = vm.createContext({document, window, URL, Set});
const template = fs.readFileSync(__dirname + '/../cmd/arxiv/templates/analytics.html', 'utf8');
const source = template.match(/<script>\n(\(function \(\) \{[\s\S]*?)<\/script>/)[1];
vm.runInContext(source, context); vm.runInContext(source, context);
assert.equal(timers.length, 1);
window.arxivSearchComplete(1, 'quick', 10);
assert.equal(events.length, 0, 'automatic page search is not a reader action');
listeners.pointerdown({isTrusted: false});
for(let i=0;i<30;i++) timers[0]();
assert.equal(events.length, 0, 'timer alone does not count readers');
listeners.keydown({isTrusted: true});
document.hidden = true; timers[0]();
assert.equal(events.length, 0, 'background tab does not emit');
document.hidden = false; timers[0](); timers[0]();
assert.equal(events.filter(e=>e[1]==='reader_activity').length, 1);
window.arxivSearchComplete(1, 'quick', 10); window.arxivSearchComplete(1, 'quick', 10);
assert.equal(events.filter(e=>e[1]==='search_completed').length, 1, 'completion is deduplicated');
window.arxivSearchComplete(2, 'secret query', 10);
assert.equal(events.length, 2, 'unrecognized modes never enter payload');
const click = (href, isTrusted=true) => listeners.click({isTrusted, target:{closest:()=>({href,closest:()=>null})}});
click('https://arxiv.gg/abs/1706.03762', false);
assert.equal(events.length, 2);
click('https://arxiv.gg/abs/1706.03762');
click('https://arxiv.org/pdf/1706.03762.pdf');
click('https://evil.example/pdf/private');
assert.deepEqual(events.map(e=>e[1]), ['reader_activity','search_completed','paper_open','paper_pdf_open']);
assert(!JSON.stringify(events).includes('1706.03762'), 'paper IDs/URLs not included in custom parameters');
console.log('reader analytics behavior checks passed');
